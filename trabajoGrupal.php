    <h1>OPERACIONES CRUD</h1>
    <h3>Introduccion</h3>
    <p>En el mundo de la programación y el desarrollo de software existen differentes operaciones que permiten administrar la 
    información almacenada en una base de datos. Una de las más importantes es el CRUD, un concepto fundamental para crear 
    aplicaciones, páginas web y sistemas informáticos.
    CRUD es un conjunto de cuatro operaciones básicas que permiten gestionar los datos: Crear, Leer, Actualizar y Eliminar. 
    Estas operaciones facilitan la administración de la información y permiten que los usuarios puedan interactuar con los 
    datos de manera sencilla y organizada.</p>

    <h1> create </h1>
    <p>CREATE es una de las cuatro operaciones fundamentales de CRUD (Create, Read, Update y Delete). Esta operación consiste en <br>
    crear e insertar nuevos registros o datos dentro de una base de datos. Es decir, permite almacenar información que todavía no existe en el sistema,<br>
    agregándola a una tabla para que pueda ser guardada y utilizada posteriormente.</p>
