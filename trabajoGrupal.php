    <h1>CREATE</h1>
    <p>Create es una de las cuatro operaciones fundamentales de CRUD (Create, Read, Update y Delete). Esta operación consiste en <br>
    crear e insertar nuevos registros o datos dentro de una base de datos. Es decir, permite almacenar información que todavía no
    existe en el sistema, agregándola a una tabla para que pueda ser guardada y utilizada posteriormente.</p>

    <h1>UPDATE</h1>
    <p>En el modelo CRUD (Create, Read, Update, Delete), Update (Actualizar)
    es la operación encargada de modificar o editar información que ya existe dentro de una base de datos o sistema. 
    A diferencia de Create, que introduce registros nuevos desde cero, Update localiza un dato previamente guardado 
    mediante un identificador único (como un ID) y sobrescribe uno o varios de sus campos con valores nuevos sin alterar el resto
    de la información almacenada.</p>

