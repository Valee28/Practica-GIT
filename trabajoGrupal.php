En el modelo CRUD (Create, Read, Update, Delete), Update (Actualizar) es la operación encargada de modificar o editar información que ya existe dentro de una base de datos o sistema. A diferencia de Create, que introduce registros nuevos desde cero, Update localiza un dato previamente guardado mediante un identificador único (como un ID) y sobrescribe uno o varios de sus campos con valores nuevos sin alterar el resto de la información almacenada.







