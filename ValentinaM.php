    <h1>RESUMEN DE JAVA</h1>
    <p>Java es un lenguaje de programación que permite crear aplicaciones para computadoras, páginas web y celulares.</p>

    <h3>Sintaxis de Java</h3>
    <p>Son las reglas que se deben seguir para escribir código correctamente.</p>
    <ul>
        <li>Se utiliza punto y coma (;).</li>
        <li>Las llaves agrupan instrucciones.</li>
        <li>Diferencia letras mayúsculas y minúsculas.</li>
        <li>Usa tipos de datos como int, double y String.</li>
        <li>El método main inicia el programa.</li>
    </ul>

    <h3>Estructuras Repetitivas</h3>
    <p>Sirven para repetir instrucciones varias veces.</p>
    <ul>
        <li>For: Repite una cantidad determinada de veces.</li>
        <li>While: Se repite mientras se cumpla una condición.</li>
        <li>Do While: Se ejecuta al menos una vez.</li>
    </ul>

    <h3>POO (Atributos y Métodos)</h3>
    <p>Es una forma de programar utilizando clases y objetos.</p>
    <ul>
        <li>Clases: Modelos para crear objetos.</li>
        <li>Objetos: Elementos creados desde una clase.</li>
        <li>Atributos: Datos de un objeto.</li>
        <li>Métodos: Acciones que realiza un objeto.</li>
    </ul>

    <h3>Herencia</h3>
    <p>Permite que una clase obtenga características de otra, facilitando la reutilización del código.</p>
    <ul>
        <li>Clase padre: Comparte sus características.</li>
        <li>Clase hija: Recibe esas características.</li>
    </ul>
    <p>En Java se utiliza la palabra extends.</p>

    <h3>Conclusión</h3>
    <p>Java permite crear programas y organizar el código mediante diferentes herramientas y conceptos.</p>

