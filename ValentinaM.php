    <h1>RESUMEN DE JAVA</h1>
    <p>Java es un lenguaje de programación orientado a objetos que se utiliza para desarrollar diferentes tipos de aplicaciones, como programas de escritorio, 
    aplicaciones web y aplicaciones móviles. Es un lenguaje muy conocido porque permite crear programas organizados, seguros y fáciles de mantener.</p>

    <h3>Sintaxis de Java</h3>
    <p>La sintaxis de Java es el conjunto de reglas que debemos seguir para escribir correctamente un programa. Algunas de sus características principales son:</p>
    <ul>
        <li>Las instrucciones generalmente terminan con punto y coma (;).</li>
        <li>Se utilizan llaves ({ }) para definir bloques de código.</li>
        <li>Java distingue entre mayúsculas y minúsculas.</li>
        <li>Las variables se declaran indicando su tipo de dato, como int, double, char, boolean y String.</li>
        <li>El método main es el punto de inicio de un programa básico.</li>
    </ul>

    <h3>Estructuras Repetitivas</h3>
    <p>Las estructuras repetitivas, también conocidas como ciclos o bucles, permiten ejecutar varias veces un bloque de instrucciones sin tener que escribirlas 
    repetidamente.</p>

    <p>En Java existen tres estructuras repetitivas principales:</p>
    <ul>
        <li>For: Se utiliza cuando conocemos la cantidad de veces que queremos repetir una instrucción.</li>
        <li>While: Repite las instrucciones mientras una condición sea verdadera.</li>
        <li>Do While: Ejecuta primero las instrucciones y después comprueba la condición, por lo que se ejecuta al menos una vez.</li>
    </ul>

    <h3>POO (Atributos y Métodos)</h3>
    <p>La Programación Orientada a Objetos (POO) es una forma de programar que organiza el código mediante clases y objetos.</p>

    <p>Sus elementos principales son:</p>
    <ul>
        <li>Clases: Son plantillas o modelos que permiten crear objetos.</li>
        <li>Objetos: Son elementos creados a partir de una clase.</li>
        <li>Atributos: Son las características o datos que tiene un objeto.</li>
        <li>Métodos: Son las acciones o comportamientos que puede realizar un objeto.</li>
    </ul>

    <p>La POO permite organizar mejor el código, facilitar su comprensión y reutilizar partes de un programa.</p>

<h3>Herencia</h3>
<p>La herencia es uno de los conceptos fundamentales de la Programación Orientada a Objetos. Permite que una clase herede atributos y métodos 
de otra clase, evitando repetir código y facilitando su reutilización.</p>

<p>Sus elementos principales son:</p>
<ul>
    <li>Clase padre: Es la clase que proporciona sus atributos y métodos.</li>
    <li>Clase hija: Es la clase que hereda las características de la clase padre.</li>
</ul>

<p>En Java se utiliza la palabra reservada extends para indicar que una clase hereda de otra.</p>

<h3>Conclusión</h3>
<p>En conclusión, Java es un lenguaje de programación muy importante que nos permite desarrollar programas mediante diferentes herramientas y 
conceptos.</p>
